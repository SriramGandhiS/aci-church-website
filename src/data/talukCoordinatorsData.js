export function getTalukCoordinator(district, taluk) {
  if (!district) return null;
  const cleanDist = district.replace(/\\s*Diocese/i, '').trim();
  const distData = TALUK_COORDINATORS_MAP[cleanDist];
  if (!distData) {
    // Partial match
    const foundKey = Object.keys(TALUK_COORDINATORS_MAP).find(k => 
      k.toLowerCase().includes(cleanDist.toLowerCase()) || cleanDist.toLowerCase().includes(k.toLowerCase())
    );
    if (foundKey) {
      return findInDist(TALUK_COORDINATORS_MAP[foundKey], taluk);
    }
    return null;
  }
  return findInDist(distData, taluk);
}

function findInDist(distData, taluk) {
  if (!distData) return null;
  if (taluk && distData[taluk]) return distData[taluk];
  if (taluk) {
    const matchKey = Object.keys(distData).find(k => 
      k.toLowerCase().includes(taluk.toLowerCase()) || taluk.toLowerCase().includes(k.toLowerCase())
    );
    if (matchKey) return distData[matchKey];
  }
  // Return the first available taluk coordinator as default for that district
  const firstKey = Object.keys(distData)[0];
  return distData[firstKey] || null;
}
